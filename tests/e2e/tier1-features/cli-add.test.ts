/**
 * Tier 1 Feature Test: CLI add & Code Injection
 * Tests component resolution, zero-dependency standalone code generation, directory creation, and collision handling.
 */

import * as fs from 'node:fs';
import * as path from 'node:path';
import * as os from 'node:os';
import { describe, it, expect, beforeEach, afterEach } from '../harness/test-kit.ts';
import { STARTER_SHADERS } from '../mocks/mock-registry-data.ts';

export interface AddOptions {
  cwd: string;
  components: string[];
  framework?: 'react' | 'vue' | 'svelte' | 'vanilla';
  typescript?: boolean;
  dir?: string;
  overwrite?: boolean;
}

export function generateComponentCode(componentId: string, framework: string, typescript: boolean): string {
  const comp = STARTER_SHADERS[componentId];
  if (!comp) {
    throw new Error(`Component '${componentId}' not found in registry`);
  }

  const compPascal = componentId
    .split('-')
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
    .join('');

  if (framework === 'react') {
    return `// Auto-generated by ShaderBit for ${comp.name}
import React, { useEffect, useRef } from 'react';
import { ShaderPipeline } from '@shaderbit/core';

export const ${compPascal}Shader = {
  glsl: \`${comp.glsl.replace(/`/g, '\\`')}\`,
  wgsl: \`${comp.wgsl.replace(/`/g, '\\`')}\`
};

export interface ${compPascal}Props {
  className?: string;
  speed?: number;
}

export function ${compPascal}({ className, speed = 1.0 }: ${compPascal}Props) {
  const canvasRef = useRef${typescript ? '<HTMLCanvasElement>' : ''}(null);

  useEffect(() => {
    if (!canvasRef.current) return;
    const pipeline = new ShaderPipeline({
      canvas: canvasRef.current,
      glsl: ${compPascal}Shader.glsl,
      wgsl: ${compPascal}Shader.wgsl
    });
    pipeline.init().then(() => pipeline.start());
    return () => pipeline.dispose();
  }, []);

  return <canvas ref={canvasRef} className={className} />;
}
`;
  }

  if (framework === 'vue') {
    return `<template>
  <canvas ref="canvasRef" :class="className" />
</template>

<script setup${typescript ? ' lang="ts"' : ''}>
import { ref, onMounted, onBeforeUnmount } from 'vue';
import { ShaderPipeline } from '@shaderbit/core';

const props = defineProps<{ className?: string; speed?: number }>();
const canvasRef = ref${typescript ? '<HTMLCanvasElement | null>' : ''}(null);
let pipeline${typescript ? ': ShaderPipeline | null' : ''} = null;

onMounted(async () => {
  if (!canvasRef.value) return;
  pipeline = new ShaderPipeline({
    canvas: canvasRef.value,
    glsl: \`${comp.glsl.replace(/`/g, '\\`')}\`,
    wgsl: \`${comp.wgsl.replace(/`/g, '\\`')}\`
  });
  await pipeline.init();
  pipeline.start();
});

onBeforeUnmount(() => {
  if (pipeline) pipeline.dispose();
});
</script>
`;
  }

  // Vanilla custom element
  return `import { ShaderPipeline } from '@shaderbit/core';

export class ${compPascal}Element extends HTMLElement {
  private pipeline: ShaderPipeline | null = null;
  private canvas: HTMLCanvasElement;

  constructor() {
    super();
    this.attachShadow({ mode: 'open' });
    this.canvas = document.createElement('canvas');
    this.shadowRoot!.appendChild(this.canvas);
  }

  async connectedCallback() {
    this.pipeline = new ShaderPipeline({
      canvas: this.canvas,
      glsl: \`${comp.glsl.replace(/`/g, '\\`')}\`,
      wgsl: \`${comp.wgsl.replace(/`/g, '\\`')}\`
    });
    await this.pipeline.init();
    this.pipeline.start();
  }

  disconnectedCallback() {
    if (this.pipeline) {
      this.pipeline.dispose();
      this.pipeline = null;
    }
  }
}
if (!customElements.get('shader-${componentId}')) {
  customElements.define('shader-${componentId}', ${compPascal}Element);
}
`;
}

export function runAdd(options: AddOptions): { success: boolean; writtenFiles: string[]; errors: string[] } {
  const writtenFiles: string[] = [];
  const errors: string[] = [];

  const framework = options.framework || 'react';
  const typescript = options.typescript !== undefined ? options.typescript : true;
  const ext = framework === 'vue' ? '.vue' : (typescript ? (framework === 'react' ? '.tsx' : '.ts') : (framework === 'react' ? '.jsx' : '.js'));
  const targetDir = path.resolve(options.cwd, options.dir || 'components/shaders');

  if (!fs.existsSync(targetDir)) {
    fs.mkdirSync(targetDir, { recursive: true });
  }

  for (const componentId of options.components) {
    if (!STARTER_SHADERS[componentId]) {
      errors.push(`Error: Component '${componentId}' not found in registry.`);
      continue;
    }

    const fileName = `${componentId}${ext}`;
    const filePath = path.join(targetDir, fileName);

    if (fs.existsSync(filePath) && !options.overwrite) {
      errors.push(`Error: File '${filePath}' already exists. Use --overwrite to replace.`);
      continue;
    }

    const code = generateComponentCode(componentId, framework, typescript);
    fs.writeFileSync(filePath, code, 'utf8');
    writtenFiles.push(filePath);
  }

  return {
    success: errors.length === 0,
    writtenFiles,
    errors
  };
}

describe('Tier 1: CLI add & Code Injection', () => {
  let tmpDir: string;

  beforeEach(() => {
    tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'shaderbit-add-test-'));
  });

  afterEach(() => {
    fs.rmSync(tmpDir, { recursive: true, force: true });
  });

  it('injects liquid-chrome standalone React component into target directory', () => {
    const result = runAdd({
      cwd: tmpDir,
      components: ['liquid-chrome'],
      framework: 'react',
      typescript: true,
      dir: 'src/components/shaders'
    });

    expect(result.success).toBe(true);
    expect(result.writtenFiles.length).toBe(1);
    expect(fs.existsSync(result.writtenFiles[0])).toBe(true);

    const content = fs.readFileSync(result.writtenFiles[0], 'utf8');
    expect(content).toContain('LiquidChrome');
    expect(content).toContain('@shaderbit/core');
    expect(content).toContain('#version 300 es');
    expect(content).not.toContain('three');
  });

  it('creates nested destination directories recursively if they do not exist', () => {
    const deeplyNested = 'app/features/graphics/sub/shaders';
    const result = runAdd({
      cwd: tmpDir,
      components: ['mesh-gradient'],
      dir: deeplyNested
    });

    expect(result.success).toBe(true);
    expect(fs.existsSync(path.join(tmpDir, deeplyNested, 'mesh-gradient.tsx'))).toBe(true);
  });

  it('generates Vue 3 SFC component when vue framework requested', () => {
    const result = runAdd({
      cwd: tmpDir,
      components: ['interactive-noise'],
      framework: 'vue',
      typescript: true
    });

    expect(result.success).toBe(true);
    const content = fs.readFileSync(result.writtenFiles[0], 'utf8');
    expect(content).toContain('<template>');
    expect(content).toContain('<script setup lang="ts">');
    expect(content).toContain('onMounted');
  });

  it('supports adding multiple components simultaneously in one invocation', () => {
    const result = runAdd({
      cwd: tmpDir,
      components: ['liquid-chrome', 'mesh-gradient', 'caustics']
    });

    expect(result.success).toBe(true);
    expect(result.writtenFiles.length).toBe(3);
    for (const file of result.writtenFiles) {
      expect(fs.existsSync(file)).toBe(true);
    }
  });

  it('guards against accidental file overwrite without explicit overwrite flag', () => {
    // Initial add
    const first = runAdd({ cwd: tmpDir, components: ['caustics'] });
    expect(first.success).toBe(true);

    // Second add without overwrite
    const second = runAdd({ cwd: tmpDir, components: ['caustics'] });
    expect(second.success).toBe(false);
    expect(second.errors[0]).toContain('already exists');

    // Add with overwrite flag
    const overwrite = runAdd({ cwd: tmpDir, components: ['caustics'], overwrite: true });
    expect(overwrite.success).toBe(true);
  });
});
